#!/usr/bin/env python3
"""Validate a batch CSV and turn it into the batch workflow's matrix."""

from __future__ import annotations

import argparse
import csv
import json
import os
import re
import sys
from pathlib import Path

from record_run_params import PARAMETERS, VALUE_PATTERN

# Every immich-load-test input a row can set, except the batch-controlled environment.
INPUTS = (*PARAMETERS.values(), "drain_timeout_seconds")
# Columns that describe a row but are not sent to the load test.
LABELS = ("run_order", "replicate", "workload_composition", "notes")
# GitHub's limit on jobs generated by one matrix.
MAX_ROWS = 256
FILE_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*\.csv")
WHOLE_NUMBER = re.compile(r"\d+")
DECIMAL = re.compile(r"\d+(\.\d+)?")
DURATION = re.compile(r"(\d+(\.\d+)?(ms|s|m|h))+")
MAX_CPU_CORES = 4


class PlanError(ValueError):
    pass


def is_at_least(minimum: int, value: str) -> bool:
    return bool(WHOLE_NUMBER.fullmatch(value)) and int(value) >= minimum


def is_decimal(value: str) -> bool:
    return bool(DECIMAL.fullmatch(value))


# Each input's check and the rule to report when it fails.
CHECKS = {
    "duration": (lambda v: bool(DURATION.fullmatch(v)), "a k6 duration such as 30s or 1m30s"),
    "concurrent_uploads": (lambda v: is_at_least(1, v), "a whole number of at least 1"),
    "users": (lambda v: is_at_least(1, v), "a whole number of at least 1"),
    "think_time_seconds": (is_decimal, "a number of at least 0"),
    "cpu_cores": (
        lambda v: is_at_least(1, v) and int(v) <= MAX_CPU_CORES,
        f"a whole number from 1 to {MAX_CPU_CORES}",
    ),
    "photo_ratio": (lambda v: is_decimal(v) and float(v) <= 1, "a number from 0 to 1"),
    "size_level": (lambda v: v in ("small", "medium", "large"), "small, medium, or large"),
    "resolution": (lambda v: v in ("480p", "1080p", "4k"), "480p, 1080p, or 4k"),
    "iterations": (lambda v: is_at_least(1, v), "a whole number of at least 1"),
    "fixture_seed": (lambda v: is_at_least(0, v), "a whole number"),
    "drain_timeout_seconds": (lambda v: is_at_least(0, v), "a whole number"),
}


def check_columns(columns: list[str]) -> None:
    duplicates = sorted({name for name in columns if columns.count(name) > 1})
    if duplicates:
        raise PlanError(f"duplicate columns: {', '.join(duplicates)}")
    unknown = [name for name in columns if name not in INPUTS and name not in LABELS]
    if unknown:
        raise PlanError(
            f"unknown columns: {', '.join(unknown)}. "
            f"Allowed inputs: {', '.join(INPUTS)}. Allowed labels: {', '.join(LABELS)}"
        )
    if not any(name in INPUTS for name in columns):
        raise PlanError("no load-test input columns")


def check_value(line: int, name: str, value: str) -> None:
    check, rule = CHECKS[name]
    if not check(value):
        raise PlanError(f"line {line}, column {name}: '{value}' must be {rule}")
    # Artifact names split on "_" and "=", so values cannot contain either.
    if name in PARAMETERS.values() and not VALUE_PATTERN.fullmatch(value):
        raise PlanError(f"line {line}, column {name}: '{value}' may only contain letters, digits, and '.'")


def load_rows(path: Path) -> list[dict]:
    """Return one matrix entry per CSV row, in file order."""
    # utf-8-sig also accepts the byte-order mark that Excel writes.
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.reader(handle)
        header = next(reader, None)
        if header is None:
            raise PlanError("the file is empty")
        columns = [name.strip() for name in header]
        check_columns(columns)

        rows: list[dict] = []
        for cells in reader:
            line = reader.line_num
            if not any(cell.strip() for cell in cells):
                continue
            if len(cells) != len(columns):
                raise PlanError(f"line {line}: expected {len(columns)} cells, found {len(cells)}")
            inputs: dict[str, str] = {}
            labels: list[str] = []
            for name, cell in zip(columns, cells):
                value = cell.strip()
                if not value:
                    # Left out so the load test's own default applies.
                    continue
                if name in LABELS:
                    labels.append(f"{name}={value}")
                else:
                    check_value(line, name, value)
                    inputs[name] = value
            rows.append({"row": len(rows) + 1, "labels": " ".join(labels), "inputs": json.dumps(inputs)})

    if not rows:
        raise PlanError("the file has no rows")
    if len(rows) > MAX_ROWS:
        raise PlanError(f"the file has {len(rows)} rows, but a matrix allows at most {MAX_ROWS}")
    return rows


def summary_table(file_name: str, rows: list[dict]) -> str:
    lines = [
        f"## Planned batch: `{file_name}`\n\nRows run one at a time, in this order.\n\n",
        "| Row | Labels | Inputs (blank cells use load-test defaults) |\n|---:|---|---|\n",
    ]
    for row in rows:
        inputs = ", ".join(f"{name}={value}" for name, value in json.loads(row["inputs"]).items())
        labels = row["labels"].replace("|", "\\|")
        lines.append(f"| {row['row']} | {labels} | {inputs} |\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("file_name", help="CSV file name inside the matrix directory")
    parser.add_argument(
        "--directory",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "experiments",
        help="folder holding batch CSV files (default: experiments)",
    )
    args = parser.parse_args()

    # A plain file name keeps the workflow input from reading outside the folder.
    if not FILE_NAME.fullmatch(args.file_name):
        print(
            f"Error: '{args.file_name}' must be a plain .csv file name in {args.directory.name}/, not a path.",
            file=sys.stderr,
        )
        return 1
    path = args.directory / args.file_name
    try:
        rows = load_rows(path)
    except (PlanError, OSError, UnicodeDecodeError, csv.Error) as error:
        print(f"Error: invalid batch file {args.file_name}: {error}.", file=sys.stderr)
        return 1

    matrix = json.dumps({"include": rows})
    print(matrix)
    output_path = os.environ.get("GITHUB_OUTPUT")
    if output_path:
        with open(output_path, "a", encoding="utf-8") as output:
            output.write(f"matrix={matrix}\n")
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary_path:
        with open(summary_path, "a", encoding="utf-8") as summary:
            summary.write(summary_table(args.file_name, rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
